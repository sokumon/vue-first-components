// Port of wc/sweep/inputs/t-core.cjs
const C = (p, s, o) => p.click(s, { timeout: 3000, ...(o || {}) }).catch((e) => console.log('  click', s, e.message.split('\n')[0].slice(0, 80)))
require('./lib.cjs')('core.html', async ({ p, r, txt, ev, W }) => {
  const state = () => txt('#state')
  r('button label prop renders', (await txt('#b-label')) === 'Label prop', await txt('#b-label'))
  r('button default slot (child text) renders', (await txt('#b-slot')).includes('Slot text'), await txt('#b-slot'))
  r('tailwind applied to button', await p.$eval('#b-label button', e => getComputedStyle(e).backgroundColor !== 'rgba(0, 0, 0, 0)'))
  await C(p, '#b-load button'); await W(100)
  r('jQuery click handler -> .attr(loading,true) disables button', await p.$eval('#b-load button', e => e.disabled).catch(() => false))
  await p.fill('#ti input', 'Grace'); await W(50)
  r('text-input update:modelValue -> state', (await state()).startsWith('Grace|'), await state())
  r('checkbox starts unchecked (prop false)', !(await p.$eval('#cb input', e => e.checked)))
  r('CheckField starts unchecked (prop 0)', !(await p.$eval('#fw input', e => e.checked)))
  await C(p, '#cb input'); await W(50)
  r('checkbox model', (await state()).split('|')[1] === 'true', await state())
  await C(p, '#sw [role=switch]'); await W(50)
  r('switch model', (await state()).split('|')[2] === 'true', await state())
  await C(p, '#sel [data-slot=trigger]'); await W(300)
  await C(p, '[role=option]:has-text("Blue")').catch(e => console.log('  sel click', e.message.slice(0, 80))); await W(100)
  r('select options prop + model', (await state()).split('|')[3] === 'blue', await state())
  r('badge', (await txt('#badge')) === 'Draft')
  r('avatar renders', (await p.$eval('#av', e => e.innerHTML.length)) > 20)
  await C(p, '#dd button'); await W(300)
  await C(p, '[role=menuitem]:has-text("Delete")').catch(e => console.log('  dd click', e.message.slice(0, 80))); await W(100)
  r('dropdown (function in options via .prop)', (await ev(() => S.picked)) === 'Delete', await ev(() => S.picked))
  await C(p, '#open-dlg button'); await W(400)
  const dlg = await p.$('[role=dialog]')
  r('dialog opens via .prop(open,true)', !!dlg)
  const dt = dlg ? (await dlg.innerText()).replace(/\n/g, ' / ') : ''
  r('dialog title prop (title attr -> prop, no native tooltip on host)', dt.includes('Hello from es-dialog') && await ev(() => !document.getElementById('dlg').hasAttribute('title')), dt.slice(0, 80))
  r('dialog body slot inside teleported dialog, inside <es-portal>', dt.includes('Dialog body via slot') && await ev(() => !!document.querySelector('es-portal #dlg-body')))
  r('slot content updated by jQuery while closed shows on open', dt.includes('name=Grace'), dt)
  await C(p, '#dlg-rename button'); await W(100)
  r('nested es-button in teleported dialog: jQuery handler fires', (await txt('#dlg-body')).includes('name=Linus') && (await state()).startsWith('Linus|'), (await txt('#dlg-body')) + ' | ' + await state())
  r('button slot updated by jQuery', (await txt('#b-dyn')) === 'Hi Linus', await txt('#b-dyn'))
  await p.keyboard.press('Escape'); await W(300)
  r('dialog Escape -> update:open false', (await state()).split('|')[4] === 'false' && (await ev(() => document.querySelectorAll('[role=dialog]').length)) === 0, await state())
  r('closed dialog body still findable by $(#id) (in <es-slots> inside host)', await ev(() => $('#dlg-body').length === 1 && $('#dlg-body').closest('#dlg').length === 1))
  await C(p, '#fw input'); await W(50)
  r('@framework/ui CheckField (0|1) model', (await state()).split('|')[5] === '1', await state())
  const before = await ev(() => ({ body: document.body.children.length, dialogs: document.querySelectorAll('[role=dialog]').length, portal: document.querySelector('es-portal').children.length }))
  await C(p, '#show-dlg2 button'); await W(400)
  const d2 = await p.$('[role=dialog]:has-text("Second dialog")')
  r('$(`<es-dialog open>`) from a template string mounts open', !!d2 && (await d2.innerText()).includes('name=Linus'))
  await C(p, '#dlg2-kill button'); await W(400)
  const after = await ev(() => ({ host: !!document.getElementById('dlg2'), body: document.body.children.length, dialogs: document.querySelectorAll('[role=dialog]').length, kill: !!document.getElementById('dlg2-kill'), portal: document.querySelector('es-portal').children.length }))
  r('.remove() from inside its own dialog: unmounted, no leaked teleport', !after.host && !after.kill && after.dialogs === before.dialogs && after.body === before.body, JSON.stringify({ before, after }))
  // reopen first dialog after all this
  await C(p, '#open-dlg button'); await W(300)
  r('dialog reopens, body slot still live node with handler', (await ev(() => document.querySelectorAll('[role=dialog]').length)) === 1 && await ev(() => document.querySelector('[role=dialog] #dlg-body') === $('#dlg-body')[0]))
  await p.keyboard.press('Escape'); await W(300)
  await p.screenshot({ path: __dirname + '/shot-core.png', fullPage: true })
})
