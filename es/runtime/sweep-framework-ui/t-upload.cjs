// jQuery-driven re-run of wc/sweep/framework-ui/t-upload.cjs + Desk-style operations.
require('./lib.cjs')('upload.html', async ({ p, r: R, txt, st, ev, W, vis, safe, calls, pageErrs, mark }) => {
  let s, tag = 'es-fw-file-upload-dialog'
  const r = (k, v, x) => R(tag, k, v, x), T = (x) => { tag = x }
  await safe(tag, 'core', async () => {
    r('closed dialog renders nothing', !(await p.$('[role=dialog]')))
    r('title attribute became the prop (no native tooltip on host)', await ev(() => !document.getElementById('c-fud').hasAttribute('title') && $('#c-fud').prop('title') === 'Add files'))
    await p.click('#open'); await W(600)
    const d = await p.$('[role=dialog]')
    r('.prop(open,true) opens dialog (teleported into es-portal)', !!d && /Upload from device/.test(await d.innerText()) && await ev(() => !!document.querySelector('[role=dialog]').closest('es-portal')), d ? (await d.innerText()).replace(/\s+/g, ' ').slice(0, 120) : '')
    const fi = await p.$('input[type=file]')
    await fi.setInputFiles([{ name: 'a.txt', mimeType: 'text/plain', buffer: Buffer.from('aa') }, { name: 'big.txt', mimeType: 'text/plain', buffer: Buffer.alloc(5000, 1) }, { name: 'x.png', mimeType: 'image/png', buffer: Buffer.from('png') }])
    await W(400)
    const dt = await txt('[role=dialog]')
    r('restrictions object prop enforced client-side (size + type)', /a\.txt/.test(dt) && /(too large|exceeds|larger|size)/i.test(dt) && /(not allowed|type)/i.test(dt), dt.slice(0, 300))
    await p.getByRole('dialog').getByRole('button', { name: 'Upload', exact: true }).click().catch((e) => console.log('  upload btn', e.message.slice(0, 60))); await W(1200)
    s = await st()
    r('Upload -> default transport POST /api/method/upload_file', calls.some((c) => c.method === 'upload_file'), calls.map((c) => c.method).join(','))
    r('committed event with file_url, uploading true/false events', s.committed.includes('/files/a.txt') && s.uploading.includes(true) && s.uploading.includes(false), JSON.stringify(s))
    r('dialog closed after commit (update:open)', !s.open && !(await p.$('[role=dialog]')), JSON.stringify([s.open]))
    await p.click('#open'); await W(500)
    await p.keyboard.press('Escape'); await W(400)
    s = await st(); r('keyboard Escape closes -> update:open false', !s.open && !(await p.$('[role=dialog]')), JSON.stringify(s.open))
  })
  T('es-fw-attachments-list')
  await safe(tag, 'core', async () => {
    r('empty state', /No attachments yet/.test(await txt('#c-al')))
    await p.click('#c-al button:has-text("Attach")'); await W(700)
    const fi2 = await p.$('#c-al input[type=file]')
    await ev(() => { window.__trayText = ''; new MutationObserver(() => { const t = document.getElementById('c-tray') ? $('es-fw-upload-tray').text() : ''; if (t.length > window.__trayText.length) window.__trayText = t }).observe(document.body, { subtree: true, childList: true, characterData: true }) })
    await fi2.setInputFiles({ name: 'b.md', mimeType: 'text/markdown', buffer: Buffer.from('# b') }); await W(300)
    await p.getByRole('dialog').getByRole('button', { name: 'Upload', exact: true }).click().catch(() => {}); await W(1200)
    s = await st()
    r('uses transport fn prop (.prop(transport, () => fn)) + v-model', (await ev(() => window.__tx)) === 1 && s.files.length === 1 && s.files[0].file_url === '/files/custom-b.md', JSON.stringify(s.files) + ' tx=' + (await ev(() => window.__tx)))
    r('renders the file row', /b\.md/.test(await txt('#c-al')))
    T('es-fw-upload-tray')
    const tray = await ev(() => window.__trayText)
    r('shows the tray-mode batch (b.md)', /b\.md|upload/i.test(tray), JSON.stringify(tray.slice(0, 120)))
    T('es-fw-attachments-list')
    await p.hover('#c-al a'); await p.click('#c-al button[aria-label=Remove]'); await W(300)
    s = await st(); r('remove -> v-model []', s.files.length === 0, JSON.stringify(s.files))
  })
  T('page'); r('no page errors in core scenarios', pageErrs().length === 0, pageErrs().join('|'))
  const m0 = mark()
  T('es-fw-file-upload-dialog')
  await safe(tag, 'desk', async () => {
    await p.click('#open'); await W(500)
    await ev(() => $('#c-fud').detach().appendTo('#desk')); await W(300)
    r('.detach().appendTo() while open keeps the dialog open', !!(await p.$('[role=dialog]')))
    await ev(() => $('#c-fud').remove()); await W(500)
    r('.remove() while open: dialog and overlay gone, page not inert', !(await p.$('[role=dialog]')) && await ev(() => getComputedStyle(document.body).pointerEvents !== 'none'), await ev(() => document.body.style.cssText))
    // re-create from an HTML string inside a template, open by attribute
    await ev(() => { const $w = $('<div class="modal-host"><es-fw-file-upload-dialog id="c-fud2" open title="Second"></es-fw-file-upload-dialog></div>'); own($w.find('es-fw-file-upload-dialog'), 'update:open', (v) => { S.open = v; if (!v) $('#c-fud2').removeAttr('open') }); $w.appendTo('#desk') }); await W(500)
    r('open="" attribute opens a dialog created from an HTML string', /Upload from device/.test(await txt('[role=dialog]')), await txt('[role=dialog]'))
    await p.click('[role=dialog] button:has-text("Cancel")').catch(() => p.keyboard.press('Escape')); await W(400)
    r('Cancel -> update:open false, the page removes the attribute, dialog closed', !(await p.$('[role=dialog]')) && !(await ev(() => document.getElementById('c-fud2').hasAttribute('open'))))
    await ev(() => $('#c-fud2').attr('open', '')); await W(500)
    r('.attr(open, "") reopens', !!(await p.$('[role=dialog]')))
    await p.keyboard.press('Escape'); await W(300)
  })
  T('es-fw-attachments-list')
  await safe(tag, 'desk', async () => {
    await ev(() => $('#c-al').prop('modelValue', [{ file_url: '/files/x.txt', file_name: 'x.txt', is_private: 0 }])); await W(200)
    r('.prop(modelValue) shows rows', /x\.txt/.test(await txt('#c-al')))
    await ev(() => $('#c-al').detach().appendTo('#desk')); await W(200)
    r('detach/append keeps rows', /x\.txt/.test(await txt('#c-al')))
    await ev(() => $('#c-al').remove()); await W(200)
    r('.remove() no errors', pageErrs(m0).length === 0, pageErrs(m0).join('|'))
  })
}, {
  wait: 1200,
  api: (m) => (m === 'upload_file' ? { name: 'F1', file_name: 'a.txt', file_url: '/files/a.txt', is_private: 0 } : undefined),
})
