// jQuery-driven re-run of wc/sweep/framework-ui/t-formlayout.cjs + Desk-style operations.
require('./lib.cjs')('formlayout.html', async ({ p, r, txt, st, ev, W, vis, safe, pageErrs, mark }) => {
  const t = 'es-fw-form-layout'
  let s
  // doc as the component sees it (the element keeps the object it was given or the one update:doc sent)
  const elDoc = () => ev(() => JSON.parse(JSON.stringify($('#c-form').prop('doc'))))
  await safe(t, 'core', async () => {
    s = await st()
    const tabs = await p.$$eval('#c-form [role=tab]', (e) => e.map((x) => x.innerText.trim()).join(','))
    r(t, 'tabs strip rendered', tabs === 'Details,More', tabs)
    r(t, 'update:activeTab announced on mount', s.active === 'details', s.active)
    r(t, 'fields rendered with labels', /Subject/.test(await txt('#c-form')) && /Status/.test(await txt('#c-form')))
    r(t, 'reason hidden by dependsOn', !(await p.isVisible('#c-form [data-fieldname=reason]')))
    await p.fill('#c-form [data-fieldname=subject] input', 'Fix it'); await W(50)
    s = await st(); r(t, 'typing writes into the page doc (in-place mutation of the object given with .prop)', s.doc.subject === 'Fix it', s.doc.subject + ' docEvents=' + s.docEvents)
    await p.click('#c-form [data-fieldname=status] button'); await W(300)
    await p.click('[role=option]:has-text("Closed")'); await W(300)
    s = await st(); r(t, 'select writes doc.status', s.doc.status === 'Closed', s.doc.status)
    r(t, 'dependsOn re-evaluates after in-form edit', await p.isVisible('#c-form [data-fieldname=reason]'))
    r(t, 'select trigger shows Closed (Vue saw in-form edit)', /Closed/.test(await txt('#c-form [data-fieldname=status]')), await txt('#c-form [data-fieldname=status]'))
    await p.click('#c-form [data-fieldname=done] button[role=checkbox], #c-form [data-fieldname=done] input[type=checkbox]'); await W(150)
    r(t, 'ui.on.change function in layout object fires', JSON.stringify(await ev(() => window.__commits)) === '[1]', JSON.stringify(await ev(() => window.__commits)))
    await p.click('#c-form [role=tab]:has-text("More")'); await W(300)
    s = await st(); r(t, 'tab click -> update:tab + update:activeTab', s.tab === 'more' && s.active === 'more', JSON.stringify([s.tab, s.active]))
    r(t, 'Table field inside FormLayout renders', /Add Row/.test(await txt('#c-form')))
    await p.click('#c-form button:has-text("Add Row")'); await W(300)
    s = await st(); r(t, 'Table add row in FormLayout', s.doc.items.length === 1, JSON.stringify(s.doc.items))
    const tr = await p.$$eval('#c-form .grid-row', (e) => e.map((x) => x.querySelectorAll('.grid-cell[data-fieldname=item] input, .grid-cell[data-fieldname=item] textarea').length))
    r(t, 'Table row editor drawn inside FormLayout', tr.length === 1 && tr[0] === 1, JSON.stringify(tr))
    if (tr[0]) { await p.click('#c-form .grid-cell[data-fieldname=item] input'); await p.keyboard.type('Bolt'); await p.keyboard.press('Tab'); await W(200) }
    s = await st(); r(t, 'typing in Table cell writes the child row', s.doc.items[0] && s.doc.items[0].item === 'Bolt', JSON.stringify(s.doc.items))
    await p.click('#c-form [role=tab]:has-text("Details")'); await W(300)
    await p.focus('#c-form [role=tab][aria-selected=true]'); await p.keyboard.press('ArrowRight'); await W(200)
    s = await st(); r(t, 'keyboard ArrowRight moves tab', s.active === 'more', s.active)
    await p.click('#c-form [role=tab]:has-text("Details")'); await W(300)
    await p.click('#go-more'); await W(200)
    s = await st(); r(t, '.prop(tab, more) from the page selects the tab', s.active === 'more', s.active)
    await p.click('#c-form [role=tab]:has-text("Details")'); await W(300)
    await p.click('#set-subject'); await W(200)
    r(t, 'page mutates doc.subject + .prop(doc, sameObject) reaches the field', (await p.inputValue('#c-form [data-fieldname=subject] input')) === 'From host', await p.inputValue('#c-form [data-fieldname=subject] input'))
    await p.click('#replace-doc'); await W(200)
    r(t, 'page replaces doc (.prop(doc, newObject)) reaches the field', (await p.inputValue('#c-form [data-fieldname=subject] input')) === 'Replaced', await p.inputValue('#c-form [data-fieldname=subject] input'))
    await p.fill('#c-form [data-fieldname=subject] input', 'After replace'); await W(50)
    s = await st(); r(t, 'edits after replace land in the new page doc', s.doc.subject === 'After replace', s.doc.subject)
    // page mutation through the object the element hands back (Desk: frm.doc is the live object)
    await ev(() => { const d = $('#c-form').prop('doc'); d.status = 'Open' }); await W(150)
    r(t, 'page mutates $(el).prop(doc).status -> dependsOn hides reason (no re-set)', !(await p.isVisible('#c-form [data-fieldname=reason]')), await vis('#c-form [data-fieldname=reason]'))
  })
  await safe(t, 'desk', async () => {
    const m0 = mark()
    await ev(() => $('#c-form').detach().appendTo('#desk')); await W(200)
    r(t, '.detach().appendTo() keeps doc + active tab', (await p.inputValue('#c-form [data-fieldname=subject] input')) === 'After replace')
    await p.fill('#c-form [data-fieldname=subject] input', 'Moved'); await W(50)
    r(t, 'edits after move still reach the page', (await st()).doc.subject === 'Moved')
    // Desk: form section HTML built from a string with the form inside, props set before append
    await ev(() => {
      const $w = $('<div class="form-page"><div class="form-message">msg</div><div class="form-body"><es-fw-form-layout id="c-form2"></es-fw-form-layout></div></div>')
      $w.find('es-fw-form-layout').prop('layout', LAYOUT()).prop('doc', { subject: 'Second', status: 'Closed', reason: 'dup', done: 1, items: [] })
      $w.appendTo('#desk')
    }); await W(200)
    r(t, 'second form from an HTML template: own doc, dependsOn shows reason', (await p.inputValue('#c-form2 [data-fieldname=subject] input')) === 'Second' && await p.isVisible('#c-form2 [data-fieldname=reason]'))
    const ids = await p.$$eval('#c-form input[id], #c-form2 input[id]', (e) => e.map((x) => x.id))
    r(t, 'ids unique across two forms (one useId counter)', new Set(ids).size === ids.length, ids.length)
    // .empty(): remount, props kept
    await ev(() => $('#c-form2').empty()); await W(200)
    r(t, '.empty() on host remounts with doc kept', (await p.inputValue('#c-form2 [data-fieldname=subject] input').catch(() => 'GONE')) === 'Second')
    // .html('') on the wrapper: the form is torn down by jQuery cleanData
    await ev(() => $('#c-form2').closest('.form-page').html('<p id="gone">gone</p>')); await W(200)
    r(t, '.html() on an ancestor unmounts the form cleanly', !(await p.$('#c-form2')) && pageErrs(m0).length === 0, pageErrs(m0).join('|'))
    // clone: props are not cloned -> doc missing; FormLayout requires doc
    const m1 = mark()
    await ev(() => { const $c = $('#c-form').clone().attr('id', 'c-form3'); $c.prop('layout', LAYOUT()).prop('doc', { subject: 'Clone' }); $c.appendTo('#desk') }); await W(200)
    r(t, '.clone() + .prop(layout/doc) before append renders the clone', (await p.inputValue('#c-form3 [data-fieldname=subject] input').catch(() => 'GONE')) === 'Clone', pageErrs(m1).join('|'))
    await ev(() => $('#c-form3').remove()); await W(150)
    r(t, '.remove() of the clone', !(await p.$('#c-form3')) && (await p.inputValue('#c-form [data-fieldname=subject] input')) === 'Moved')
    r(t, 'no errors in Desk operations', pageErrs(m0).length === 0, pageErrs(m0).join('|'))
  })
}, { wait: 1200 })
