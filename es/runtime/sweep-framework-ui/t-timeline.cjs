// jQuery-driven re-run of wc/sweep/framework-ui/t-timeline.cjs + Desk-style operations.
require('./lib.cjs')('timeline.html', async ({ p, r: R, txt, st, ev, W, vis, safe, pageErrs, mark }) => {
  let s, tag = 'es-fw-activity-timeline'
  const r = (k, v, x) => R(tag, k, v, x), T = (x) => { tag = x }
  await safe(tag, 'core', async () => {
    const types = await p.$$eval('#c-tl [data-type]', (e) => e.map((x) => x.dataset.type).join(','))
    r('renders every activity type in order', types === 'log,version,comment,email,attachment_log', types)
    const tl = await txt('#c-tl')
    r('rows show content', /created this/.test(tl) && /Open → Closed/.test(tl) && /Looks good/.test(tl) && /spec\.pdf/.test(tl), tl.slice(0, 300))
    r('#icon-log named slot lands in the log row gutter', await ev(() => { const i = document.querySelector('#c-tl .logicon'); return !!i && !!i.closest('.activity') && i.closest('.activity').querySelector('[data-type=log]') !== null }))
    await p.click('#c-tl button:has-text("Older activity")'); await W(200)
    s = await st(); r('paginate.fetchNextPage fn prop called by Load More', s.more === 1, s.more)
    r('#empty slot jQuery-updated', /Quiet here \(1\)/.test(await txt('#c-tl-empty')), await txt('#c-tl-empty'))
    r('exposed scrollToLatest/scrollToRow reachable on element', await ev(() => { const el = document.getElementById('c-tl'); return typeof el.scrollToLatest === 'function' && typeof el.scrollToRow === 'function' }))
    const ok = await ev(() => { try { document.getElementById('c-tl').scrollToLatest(); return true } catch (e) { return e.message } })
    r('el.scrollToLatest() callable', ok === true, ok)
    const tcm = await p.$$eval('#c-tl-tpl .tplcomment', (e) => e.map((x) => x.textContent))
    r('scoped #item-comment <template> gets {activity}', tcm.length === 1 && tcm[0] === 'Comment c1 by Ada Lovelace', JSON.stringify(tcm))
  })
  T('es-fw-timeline-container')
  await safe(tag, 'core', async () => r('default slot', /container child/.test(await txt('#c-tc')) && await ev(() => document.getElementById('tc-child').closest('#c-tc') !== null)))
  T('es-fw-comment-item')
  await safe(tag, 'core', async () => {
    r('actions slot visible', await p.isVisible('#edit-btn'))
    await p.click('#edit-btn'); await W(500)
    r('.prop(editable,true) from a jQuery click -> Save/Discard', /Save/.test(await txt('#c-comment')) && /Discard/.test(await txt('#c-comment')), await txt('#c-comment'))
    const ed = await p.$('#c-comment [contenteditable=true]')
    r('editor becomes contenteditable', !!ed)
    if (ed) { await ed.click(); await p.keyboard.press('Control+End'); await p.keyboard.type(' indeed'); await p.keyboard.press('Control+Enter'); await W(300) }
    s = await st(); r('Ctrl+Enter -> save event with edited html', /indeed/.test(s.saved) && s.editing === false, JSON.stringify(s.saved))
    await p.click('#edit-btn'); await W(300); await p.click('#c-comment button:has-text("Discard")'); await W(300)
    s = await st(); r('Discard -> discard event', s.discards === 1 && s.editing === false, JSON.stringify(s))
  })
  T('es-fw-email-item')
  await safe(tag, 'core', async () => {
    const em = await txt('#c-email')
    r('header + footer slot', /Re: bug/.test(em) && /Reply to ada@example.com/.test(em), em)
    r('body content visible', /Email body here/.test(em + (await p.$eval('#c-email', (e) => e.innerHTML))), em)
  })
  T('es-fw-log-item'); await safe(tag, 'core', async () => r('standalone', /created this/.test(await txt('#c-log')), await txt('#c-log')))
  T('es-fw-version-item'); await safe(tag, 'core', async () => r('standalone', /Open\s*→\s*Closed/.test(await txt('#c-version')), await txt('#c-version')))
  T('es-fw-attachment-chip')
  await safe(tag, 'core', async () => {
    await p.click('#c-chip button'); await W(800)
    const d = await p.$('[role=dialog]')
    r('opens preview dialog with fetched markdown', !!d && /Hello from readme/.test(await d.innerText()), d ? (await d.innerText()).slice(0, 120) : 'no dialog')
    await p.keyboard.press('Escape'); await W(300)
    r('Escape closes preview', !(await p.$('[role=dialog]')))
  })
  T('page'); r('no page errors in core scenarios', pageErrs().length === 0, pageErrs().join('|'))
  // ------------------------------------------------------------ Desk-style
  const m0 = mark()
  T('es-fw-activity-timeline')
  await safe(tag, 'desk', async () => {
    // new activity: Desk pushes to its list and re-sets the prop (same array mutated, then a new array)
    await ev(() => { ACTS.push({ type: 'comment', key: 'c2', timestamp: '2026-11-20 11:00:00', author: ACTS[0].author, data: { name: 'c2', content: '<p>Second</p>', attachments: [] } }); $('#c-tl').prop('activities', ACTS) }); await W(300)
    r('page pushes into its array + .prop(activities, sameArray) shows the new row', /Second/.test(await txt('#c-tl')), (await txt('#c-tl')).slice(-120))
    await ev(() => $('#c-tl').prop('activities', ACTS.slice())); await W(300)
    r('.prop(activities, newArray) shows the new row', /Second/.test(await txt('#c-tl')))
    await ev(() => $('#c-tl').detach().appendTo('#desk')); await W(200)
    r('.detach().appendTo() keeps rows + slot', /Second/.test(await txt('#c-tl')) && !!(await p.$('#c-tl .logicon')))
    await ev(() => $('#c-tl-tpl').html('<template slot="item-comment"><em class="tpl3" data-es-text="activity.key"></em></template>')); await W(300)
    const t3 = await p.$$eval('#c-tl-tpl .tpl3', (e) => e.map((x) => x.textContent))
    r('.html(<template>) on host swaps the scoped template (both comments, c2 was pushed into the shared array)', t3.join() === 'c1,c2', JSON.stringify(t3))
    await ev(() => $('#c-tl-empty').clone().attr('id', 'c-tl-empty2').find('#tl-empty').attr('id', 'tl-empty2').end().prop('activities', []).appendTo('#desk')); await W(300)
    r('.clone() of a slot-configured timeline (+ .prop) renders the copied empty slot', /Quiet here/.test(await txt('#c-tl-empty2')), await txt('#c-tl-empty2'))
    await ev(() => { $('#c-tl-empty2').remove(); $('#c-tl').remove() }); await W(200)
    r('.remove() no errors', !(await p.$('#c-tl')) && pageErrs(m0).length === 0, pageErrs(m0).join('|'))
  })
  T('es-fw-comment-item')
  await safe(tag, 'desk', async () => {
    await ev(() => { $('#c-comment').detach().appendTo('#desk') }); await W(200)
    await p.click('#edit-btn'); await W(400)
    r('after move: jQuery handler on slot button still toggles editable', /Save/.test(await txt('#c-comment')))
    await ev(() => $('#c-comment').detach().appendTo('#app')); await W(200)
    r('detach while editing keeps the editor open', !!(await p.$('#c-comment [contenteditable=true]')))
    await p.click('#c-comment button:has-text("Discard")'); await W(200)
    await ev(() => $('#c-comment').remove()); await W(150)
    r('.remove() no errors', pageErrs(m0).length === 0, pageErrs(m0).join('|'))
  })
  T('es-fw-email-item')
  await safe(tag, 'desk', async () => {
    await ev(() => $('#email-footer .s').text('changed@example.com')); await W(50)
    r('jQuery writes into the footer slot node show in place', /Reply to changed@example.com/.test(await txt('#c-email')))
    await ev(() => $('#c-email').append('<div slot="footer" id="email-footer2">Forward</div>')); await W(200)
    r('.append() a second footer node joins the slot', /Forward/.test(await txt('#c-email')) && /changed/.test(await txt('#c-email')))
  })
  T('es-fw-attachment-chip')
  await safe(tag, 'desk', async () => {
    await ev(() => $('<div class="attachments"><es-fw-attachment-chip label="b.md" url="/files/readme.md" id="c-chip2"></es-fw-attachment-chip></div>').appendTo('#desk')); await W(200)
    await p.click('#c-chip2 button'); await W(800)
    r('chip from an HTML string opens preview', /Hello from readme/.test(await txt('[role=dialog]')))
    await ev(() => $('#c-chip2').closest('.attachments').remove()); await W(400)
    r('.remove() of the wrapper while its dialog is open: dialog goes away', !(await p.$('[role=dialog]')) && pageErrs(m0).length === 0, pageErrs(m0).join('|'))
  })
}, { wait: 1200 })
