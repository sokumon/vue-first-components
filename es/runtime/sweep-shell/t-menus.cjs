// jQuery-driven re-run of wc/sweep/shell/xo/t-menus.cjs + Desk-style operations.
require('./lib.cjs')('menus.html', async ({ p, r, txt, st, ev, W, vis, rect, inside, log, safe, errs, errCount }) => {
  const menu = '[role=menu]'
  let t = 'es-dropdown'
  await safe(t, 'core', async () => {
    const tr = await rect('#dd-trigger button')
    r(t, 'trigger: nested es-button in default slot renders', tr && tr.w > 20 && (await txt('#dd-trigger')).includes('Menu'), tr)
    await p.click('#dd-trigger button'); await W(300)
    r(t, 'opens on click -> update:open', await vis(menu) && (await st()).dd === true)
    const mr = await rect(menu)
    r(t, 'menu positioned under trigger', mr && tr && Math.abs(mr.x - tr.x) < 20 && mr.y >= tr.y + tr.h - 2 && mr.y < tr.y + tr.h + 30, { tr, mr })
    const at = await p.$eval('#dd-trigger button', (b) => b.getAttribute('aria-expanded') + '/' + b.getAttribute('data-state'))
    r(t, 'trigger button carries aria-expanded / data-state=open', at === 'true/open', at)
    r(t, 'group labels rendered', (await txt(menu)).includes('Actions') && (await txt(menu)).includes('Danger'))
    r(t, 'per-item named slot (option.slot -> slot="item-danger") inside its row', await inside('#dd-danger', menu) && (await txt('#dd-danger')).startsWith('Delete forever'), await txt('#dd-danger'))
    await p.keyboard.press('ArrowDown'); await W(80)
    const f1 = await ev(() => document.activeElement?.innerText?.trim())
    r(t, 'ArrowDown moves focus into menu', /Edit|Share/.test(f1 || ''), f1)
    await p.hover(menu + ' [role=menuitem]:has-text("Share")'); await W(400)
    r(t, 'submenu opens on hover', await vis('[role=menu] [role=menuitem]:has-text("Email")'))
    await p.click('[role=menuitem]:has-text("Email")'); await W(300)
    r(t, 'submenu item onClick fires and menu closes', (await log()).includes('email') && !(await vis(menu)) && (await st()).dd === false)
    await p.click('#dd-trigger button'); await W(300)
    await p.click(menu + ' [role=switch]'); await W(200)
    r(t, 'switch item toggles through onClick(value)', (await st()).notify === false, await log())
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'Escape closes', !(await vis(menu)) && (await st()).dd === false)
    r(t, 'focus returns to trigger button after Escape', await ev(() => !!document.activeElement?.closest('#dd-trigger')), await ev(() => document.activeElement?.tagName))
    await p.focus('#dd-trigger button'); await p.keyboard.press('Enter'); await W(300)
    r(t, 'opens from keyboard (Enter)', await vis(menu))
    await p.keyboard.press('Escape'); await W(200)
    await p.click('#dd-open'); await W(300)
    r(t, 'opens from .prop("open", true)', await vis(menu))
    await p.click(menu + ' [role=menuitem]:has-text("Delete")'); await W(300)
    r(t, 'item with slot clicked -> onClick', (await log()).includes('delete') && !(await vis(menu)))
  })
  await safe(t, 'empty (options="[]" attribute)', async () => {
    await p.click('#dd2-trigger'); await W(300)
    r(t, 'slot="trigger" plain button opens dropdown', await vis(menu))
    r(t, 'slot="empty" rendered in empty menu', await inside('#dd2-empty', menu) && await vis('#dd2-empty'))
    const t2 = await rect('#dd2-trigger'), m2 = await rect(menu)
    r(t, 'empty menu positioned under slot trigger', m2 && t2 && Math.abs(m2.x - t2.x) < 20 && m2.y >= t2.y + t2.h - 2 && m2.y < t2.y + t2.h + 30, { t2, m2 })
    await p.keyboard.press('Escape'); await W(300)
  })
  await safe(t, 'item-suffix (button JSON attribute)', async () => {
    await p.click('#dd3 button'); await W(300)
    const suf = await p.$$eval(menu + ' .dd-suffix', (es) => es.length)
    r(t, 'item-suffix slot on every row (one light-DOM node rendered 3 times)', suf === 3, suf)
    await p.keyboard.press('Escape'); await W(300)
  })
  t = 'es-context-menu'
  await safe(t, 'core', async () => {
    const a = await rect('#cm-area')
    await p.click('#cm-area', { button: 'right', position: { x: 40, y: 20 } }); await W(300)
    r(t, 'opens on right click -> update:open', await vis(menu) && (await st()).cm === true)
    const cr = await rect(menu)
    r(t, 'menu at pointer', cr && Math.abs(cr.x - (a.x + 40)) < 10 && Math.abs(cr.y - (a.y + 20)) < 10, { a, cr })
    r(t, 'disabled option is disabled', await p.$eval(menu + ' [role=menuitem]:has-text("Paste")', (e) => e.hasAttribute('data-disabled') || e.getAttribute('aria-disabled') === 'true').catch(() => false))
    await p.keyboard.press('ArrowDown'); await p.keyboard.press('Enter'); await W(300)
    r(t, 'keyboard select Copy', (await log()).includes('copy') && !(await vis(menu)) && (await st()).cm === false, await log())
    r(t, 'region slot text written by jQuery stays live', (await txt('#cm-area')).includes('(' + (await st()).log.length + ')'), await txt('#cm-area'))
    await p.click('#cm-area', { button: 'right' }); await W(300)
    await p.hover(menu + ' [role=menuitem]:has-text("More")'); await W(400)
    await p.click('[role=menuitem]:has-text("Deep")'); await W(300)
    r(t, 'submenu item', (await log()).includes('deep'))
  })

  // ---------------------------------------------------------------- Desk-style
  t = 'es-dropdown'
  await safe(t, 'desk ops', async () => {
    // Desk "actions" button group built from a string, dropdown inside
    await ev(() => $('#desk').append(`<div class="page-actions"><span class="indicator">Draft</span>
      <es-dropdown id="dd-desk"><button class="btn btn-default" id="dd-desk-btn">Actions</button></es-dropdown></div>`))
    await ev(() => $('#dd-desk').prop('options', [{ label: 'Print', onClick: () => S.log.push('print') }]))
    await p.click('#dd-desk-btn'); await W(300)
    r(t, 'created inside a larger template: plain <button> default-slot trigger opens the menu', await vis(menu) && (await txt(menu)).includes('Print'))
    await p.click('[role=menuitem]:has-text("Print")'); await W(300)
    r(t, 'item fires', (await log()).includes('print'))
    await ev(() => $('#dd-desk').html('<button id="dd-desk-btn2" class="border px-2">New trigger</button>')); await W(150)
    await p.click('#dd-desk-btn2'); await W(300)
    r(t, '.html() on host: new trigger works, options kept', await vis(menu) && (await txt(menu)).includes('Print'))
    await p.keyboard.press('Escape'); await W(300)
    const e0 = await errCount()
    await ev(() => { const $d = $('#dd-desk').detach(); $('.page-actions').prepend($d) }); await W(150)
    await p.click('#dd-desk-btn2'); await W(300)
    r(t, '.detach() + .prepend(): still opens, menu under trigger', await vis(menu) && (await errCount()) === e0)
    await ev(() => $('#dd-desk').remove()); await W(300)
    r(t, '.remove() while OPEN: menu gone, body unlocked', !(await vis(menu)) && await ev(() => getComputedStyle(document.body).pointerEvents !== 'none'), await ev(() => document.body.getAttribute('style')))
    await ev(() => $('#dd').clone().attr('id', 'dd-c').appendTo('#desk')); await W(150)
    await ev(() => $('#dd-c').prop('options', [{ label: 'Clone item', onClick: () => S.log.push('clone-item') }]))
    await p.click('#dd-c button'); await W(300)
    r(t, '.clone(): own trigger (one button), own options', (await ev(() => document.querySelectorAll('#dd-c button').length)) === 1 && (await txt(menu)).includes('Clone item'), await ev(() => document.querySelectorAll('#dd-c button').length))
    await p.keyboard.press('Escape'); await W(300)
  })
  t = 'es-context-menu'
  await safe(t, 'desk ops', async () => {
    await ev(() => $('#cm').append('<div id="cm-area2" class="border p-4 w-80">Second region</div>')); await W(100)
    await p.click('#cm-area2', { button: 'right' }); await W(300)
    r(t, '.append() a second region: right click there opens the menu too', await vis(menu))
    await p.keyboard.press('Escape'); await W(300)
  })
})
