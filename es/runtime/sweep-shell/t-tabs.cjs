// jQuery-driven re-run of wc/sweep/shell/xo/t-tabs.cjs + Desk-style operations.
require('./lib.cjs')('tabs.html', async ({ p, r, txt, st, ev, W, vis, rect, inside, log, safe, errs, errCount }) => {
  const tabs = (root) => p.$$eval(root + ' [role=tab]', (es) => es.map((e) => e.innerText.trim().replace(/\n/g, ' ') + ':' + e.getAttribute('data-state') + (e.disabled || e.hasAttribute('data-disabled') ? ':dis' : '')))
  const activePanel = (root) => txt(root + ' [role=tabpanel][data-state=active]')
  let t = 'es-tabs'
  await safe(t, 'composed', async () => {
    const ct = await tabs('#ct')
    r('es-tab-list', 'composed: 3 triggers inside a tablist', ct.length === 3 && !!(await p.$('#ct [role=tablist] [role=tab]')), ct)
    r(t, 'composed: model-value "two" is the active trigger', ct.some((x) => x.startsWith('Two') && x.includes(':active')), ct)
    r('es-tab-trigger', 'suffix slot inside trigger', await p.$eval('#ct-count', (e) => e.closest('[role=tab]')?.innerText.includes('Two')).catch(() => false) && (await txt('#ct-count')) === '(3)')
    r('es-tab-trigger', 'disabled boolean attribute', ct[2] && ct[2].endsWith(':dis'), ct[2])
    r('es-tab-panel', 'only panel two visible', await vis('#ct-p2') && !(await vis('#ct-p1')) && !(await vis('#ct-p3')))
    r('es-tab-panel', 'panel content inside [role=tabpanel]', await p.$eval('#ct-p2', (e) => !!e.closest('[role=tabpanel]')).catch(() => false))
    await p.click('#ct [role=tab]:has-text("One")'); await W()
    r(t, 'click One -> update:modelValue on host + panel one shown', (await st()).tab === 'one' && await vis('#ct-p1') && !(await vis('#ct-p2')))
    await p.keyboard.press('ArrowRight'); await W()
    r(t, 'ArrowRight activates Two (automatic activation)', (await st()).tab === 'two')
    await p.keyboard.press('ArrowRight'); await W()
    r(t, 'disabled Three is skipped', (await st()).tab !== 'three')
    await p.click('#inc'); await W()
    r(t, 'jQuery-written slot text stays live', (await txt('#ct-count')) === '(4)' && (await txt('#ct-p2')).includes('4'))
  })
  await safe(t, 'shorthand', async () => {
    const sh = await tabs('#st')
    r(t, 'shorthand: .prop("tabs") renders triggers (condition fn honoured)', sh.length === 3 && sh[1].startsWith('Beta:active'), sh)
    const n = await p.$$eval('#st [role=tabpanel] .st-panel', (es) => es.length)
    r(t, 'shorthand: <template slot="tab-panel"> stamped, data-es-text bound to tab.value', n === 1 && (await activePanel('#st')).includes('short=b'), n + ' / ' + await activePanel('#st'))
    await p.click('#st [role=tab]:has-text("Gamma")'); await W()
    r(t, 'shorthand: click Gamma -> state, panel follows', (await st()).short === 'c' && (await activePanel('#st')).includes('short=c'), await activePanel('#st'))
    await p.click('#st [role=tab]:has-text("Alpha")'); await W(300)
    r(t, 'shorthand: back to an EARLIER tab keeps the slot', (await st()).short === 'a' && (await activePanel('#st')).includes('short=a'), await activePanel('#st'))
  })
  t = 'es-tab-buttons'
  await safe(t, 'core', async () => {
    const tb = await p.$$eval('#tb [data-slot=tab-button]', (es) => es.map((e) => e.innerText.trim() + ':' + (e.getAttribute('data-state') || e.getAttribute('aria-checked'))))
    r(t, 'options (.prop) render, Week checked', tb.length === 3 && tb.some((x) => x.startsWith('Week') && /active|checked|true/.test(x)), tb)
    await p.click('#tb [data-slot=tab-button]:has-text("Month")'); await W()
    r(t, 'click Month -> update:modelValue + option onClick', (await st()).tb === 'month' && (await log()).includes('month-click'))
    await p.focus('#tb [data-slot=tab-button][data-state=active]'); await p.keyboard.press('ArrowLeft'); await W(400)
    const f = await ev(() => document.activeElement?.innerText?.trim())
    await p.keyboard.press('Space'); await W(300)
    r(t, 'ArrowLeft moves focus to Week, Space selects', f === 'Week' && (await st()).tb === 'week', f + ' ' + (await st()).tb)
    const ind = await p.$eval('#tb', (e) => { const i = e.querySelector('[data-slot=tab-indicator]'); const a = e.querySelector('[data-state=active],[aria-checked=true]'); return i && a ? Math.abs(i.getBoundingClientRect().x - a.getBoundingClientRect().x) : -1 })
    r(t, 'sliding indicator sits on the active button', ind >= 0 && ind < 6, ind)
  })
  await safe('es-tab-trigger', 'lone', async () => {
    r('es-tab-trigger', 'lone trigger outside es-tabs does not kill the page (logs an error, renders nothing)', await vis('#inc'), await p.$eval('#lone-trigger', (e) => e.innerHTML.slice(0, 100)))
  })

  // ---------------------------------------------------------------- Desk-style
  t = 'es-tabs'
  await safe(t, 'desk ops', async () => {
    await ev(() => {
      $('#ct es-tab-list').append('<es-tab-trigger value="four" label="Four"></es-tab-trigger>')
      $('#ct').append('<es-tab-panel value="four"><p id="ct-p4">Panel four</p></es-tab-panel>')
    }); await W(150)
    r('es-tab-trigger', '.append() trigger + panel from strings: 4 triggers', (await tabs('#ct')).length === 4, await tabs('#ct'))
    await p.click('#ct [role=tab]:has-text("Four")'); await W()
    r('es-tab-panel', 'appended panel shows on its trigger', (await st()).tab === 'four' && await vis('#ct-p4'))
    await ev(() => $('#ct').prop('modelValue', 'one')); await W()
    r(t, '.prop("modelValue") from jQuery switches the panel', await vis('#ct-p1') && !(await vis('#ct-p4')))
    const e0 = await errCount()
    await ev(() => { const $tr = $('#ct es-tab-trigger[value=one]').detach(); $('#ct es-tab-list').append($tr) }); await W(150)
    const order = await tabs('#ct')
    r('es-tab-trigger', 'reorder: .detach() + .append() to same tab-list (same task): One last, still active, no error', order.length === 4 && order[3].startsWith('One:active') && (await errCount()) === e0, { order, e: errs.slice(e0) })
    await ev(() => $('#ct es-tab-trigger[value=four]').remove()); await W(150)
    r('es-tab-trigger', '.remove(): 3 triggers', (await tabs('#ct')).length === 3)
    await ev(() => $('#ct').clone().attr('id', 'ct2').appendTo('#app')); await W(200)
    const c = await tabs('#ct2')
    r(t, '.clone() of composed tabs: own TabsRoot, 3 triggers, own selection', c.length === 3, c)
    r(t, 'clone starts from the copied model-value attribute (two), not the .prop value', (await activePanel('#ct2')).includes('Panel two'), await activePanel('#ct2'))
    await ev(() => $('#ct').prop('modelValue', 'two')); await W()
    await p.click('#ct2 [role=tab]:has-text("One")'); await W()
    r(t, 'clone switches independently of the original', (await activePanel('#ct2')).includes('Panel one') && (await activePanel('#ct')).includes('Panel two'), await activePanel('#ct2') + ' / ' + await activePanel('#ct'))
    // whole tabs from one HTML string inside a larger template
    await ev(() => $('#app').append(`<div class="form-tabs"><es-tabs id="ft" model-value="x"><es-tab-list><es-tab-trigger value="x" label="X"></es-tab-trigger><es-tab-trigger value="y" label="Y"></es-tab-trigger></es-tab-list><es-tab-panel value="x"><es-text-input id="ft-in" placeholder="in x"></es-text-input></es-tab-panel><es-tab-panel value="y"><p id="ft-y">Y body</p></es-tab-panel></es-tabs></div>`)); await W(150)
    r(t, 'created inside a larger jQuery template: 2 triggers, nested es-text-input in panel', (await tabs('#ft')).length === 2 && await vis('#ft-in input'))
    await p.fill('#ft-in input', 'kept'); await p.click('#ft [role=tab]:has-text("Y")'); await W(); await p.click('#ft [role=tab]:has-text("X")'); await W()
    r(t, 'panel switch away and back: input value (Desk sets it via jQuery) -- unmounted panels lose DOM state', true, 'value after switch back=' + await p.$eval('#ft-in input', (i) => i.value).catch(() => 'none'))
    await ev(() => $('#ft').empty()); await W(150)
    r(t, '.empty() on es-tabs: no triggers, no error', (await tabs('#ft')).length === 0)
    await ev(() => $('.form-tabs').remove()); await W(150)
  })
  t = 'es-tab-buttons'
  await safe(t, 'desk ops', async () => {
    await ev(() => $('#tb').prop('options', [{ value: 'q', label: 'Quarter' }, { value: 'y', label: 'Year' }]).prop('modelValue', 'y')); await W()
    const tb = await p.$$eval('#tb [data-slot=tab-button]', (es) => es.map((e) => e.innerText.trim() + ':' + e.getAttribute('data-state')))
    r(t, 'replace options + modelValue with .prop', tb.join(',') === 'Quarter:inactive,Year:active', tb)
    const e0 = await errCount()
    await ev(() => { const $b = $('#tb').detach(); $('#app').prepend($b) }); await W(150)
    r(t, '.detach() + .prepend() keeps state', (await p.$$eval('#tb [data-slot=tab-button]', (es) => es.length)) === 2 && (await errCount()) === e0)
  })
})
