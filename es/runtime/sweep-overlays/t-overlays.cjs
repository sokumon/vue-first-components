// jQuery-driven re-run of wc/sweep/overlays/t-overlays.cjs + Desk-style operations.
require('./lib.cjs')('overlays.html', async ({ p, r, txt, st, ev, W, vis, rect, inside, log, safe }) => {
  const dlg = '[role=dialog]'
  const S = st
  const later = []
  const desk = (t, f) => later.push([t, f])
  const bodyFree = () => ev(() => getComputedStyle(document.body).pointerEvents !== 'none' && document.body.style.overflow !== 'hidden')
  const portalCount = () => ev(() => document.querySelectorAll('es-portal [role=dialog], es-portal [data-slot=content], es-portal [role=menu]').length)
  // ---------- Dialog
  let t = 'es-dialog'
  await safe(t, 'core', async () => {
    r(t, 'closed: no [role=dialog], slot nodes hidden', !(await p.$(dlg)) && !(await vis('#d-body')))
    await p.click('#open-d'); await W(300)
    r(t, 'opens from .prop("open", true)', await vis(dlg))
    r(t, 'slot="title" inside dialog header', await inside('#d-title', dlg + ' header') && (await txt('#d-title')) === 'Custom title for Ada', await txt('#d-title'))
    r(t, 'default slot replaces message prop', await inside('#d-body', dlg) && !(await p.textContent(dlg)).includes('ignored when'), await txt(dlg))
    r(t, 'icon prop renders lucide badge', !!(await p.$(dlg + ' [data-slot=icon] .lucide-info')))
    const btns = await p.$$eval(dlg + ' [data-slot=actions] button', (bs) => bs.map((b) => b.innerText.trim()))
    r(t, 'actions prop (.prop array of objects) renders buttons', btns.join('|') === 'Cancel|Save', btns.join('|'))
    await p.fill('#d-input', 'Grace'); await W()
    r(t, 'input in teleported slot: delegated jQuery handler sees it, live title updates', (await S()).name === 'Grace' && (await txt('#d-title')).includes('Grace'), (await S()).name)
    await p.click(dlg + ' [data-slot=actions] button:has-text("Save")'); await W(400)
    const s = await S()
    r(t, 'action onClick({close}) fn: saved+1, closes, update:open/close/after-leave on host', s.saved === 1 && s.d === false && !(await vis(dlg)) && s.log.includes('d-close') && s.log.includes('d-after'), s)
    r(t, 'element keeps open=false after update:open (like an <input>)', await ev(() => document.getElementById('d').open === false))
    await p.click('#open-d'); await W(300)
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'Escape closes', (await S()).d === false && !(await vis(dlg)))
    await p.click('#open-d'); await W(300)
    r(t, 'close button present by default', !!(await p.$(dlg + ' button[aria-label=Close]')))
    await p.click(dlg + ' button[aria-label=Close]'); await W(300)
    r(t, 'close button closes', (await S()).d === false && !(await vis(dlg)))
    await p.click('#open-d'); await W(300)
    await p.mouse.click(5, 5); await W(300)
    r(t, 'outside click closes', (await S()).d === false)
    r(t, 'slot nodes back in hidden <es-slots> after close, $("#d-body") still finds them', !(await vis('#d-body')) && await ev(() => !!$('#d-body').closest('es-slots').length && $('#d-body').closest('#d').length === 1))
    r(t, 'body pointer-events/overflow restored after close', await bodyFree())
    // focus trap / Tab
    await p.click('#open-d'); await W(300)
    for (let i = 0; i < 6; i++) await p.keyboard.press('Tab')
    r(t, 'Tab keeps focus inside the dialog (focus trap)', await ev(() => !!document.activeElement.closest('[role=dialog]')))
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'focus returns to the opener after Escape', await ev(() => document.activeElement && document.activeElement.id === 'open-d'), await ev(() => document.activeElement && document.activeElement.outerHTML.slice(0, 60)))
  })
  await safe(t, 'model/dismissible', async () => {
    await p.click('#open-dm'); await W(300)
    r(t, 'modelValue dialog opens', await vis(dlg))
    r(t, 'message prop renders', (await txt(dlg)).includes('Message prop text'))
    r(t, 'slot="actions" replaces footer, nested es-button inside', await inside('#dm-ok', dlg + ' [data-slot=actions]') && await vis('#dm-ok button'))
    r(t, 'show-close-button="false" hides close button', !(await p.$(dlg + ' button[aria-label=Close]')))
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'dismissible="false": Escape does not close', await vis(dlg))
    await p.mouse.click(5, 5); await W(300)
    r(t, 'dismissible="false": outside click does not close', await vis(dlg))
    await p.click('#dm-ok button'); await W(300)
    r(t, 'jQuery click on nested es-button in actions slot closes via .prop("modelValue", false)', !(await vis(dlg)) && (await log()).includes('dm-ok'))
    await p.click('#open-d3'); await W(300)
    r(t, 'bare: slot without header/actions chrome', await inside('#d3-body', dlg) && !(await p.$(dlg + ' header')) && (await txt('#d3-body')).includes('Grace'))
    await p.click('#d3-x'); await W(300)
    r(t, 'bare closes from slot button (delegated handler)', !(await vis(dlg)))
  })
  // Desk operations on a dialog
  desk(t, async (t) => {
    // .html() on a closed dialog host: new slot content, still works
    await ev(() => $('#d3').html('<div id="d3-new" class="p-6">Replaced by .html() <button id="d3-new-x">x</button></div>'))
    await ev(() => $('#d3-new-x').on('click', () => $('#d3').prop('open', false)))
    await p.click('#open-d3'); await W(300)
    r(t, '.html() on closed host: new content shows when opened', await inside('#d3-new', dlg) && !(await p.$('#d3-body')), await txt(dlg).catch(() => ''))
    await p.click('#d3-new-x'); await W(300)
    r(t, '.html() content: handler bound after .html() closes', !(await vis(dlg)))
    // .html() while open
    await p.click('#open-d3'); await W(300)
    await ev(() => $('#d3').html('<div id="d3-new2" class="p-6">Second</div>')); await W(300)
    const after = await ev(() => ({ n: document.querySelectorAll('[role=dialog]').length, txt: document.querySelector('[role=dialog]') && document.querySelector('[role=dialog]').innerText, inDlg: !!(document.getElementById('d3-new2') && document.getElementById('d3-new2').closest('[role=dialog]')) }))
    r(t, '.html() while open: one dialog, new content inside (state reset but open prop kept)', after.n === 1 && after.inDlg, after)
    await p.keyboard.press('Escape'); await W(300)
    r(t, '.html() while open then Escape: closes, body free', !(await p.$(dlg)) && await bodyFree())
    // .empty() on a host
    await ev(() => $('#d3').empty()); await W(50)
    await p.click('#open-d3'); await W(300)
    r(t, '.empty(): dialog still opens (no slot content)', !!(await p.$(dlg)) && !(await p.$('#d3-new2')))
    await p.keyboard.press('Escape'); await W(300)
    // .detach() + .appendTo() while open keeps it open and state
    await p.click('#open-d'); await W(300)
    await p.fill('#d-input', 'Kept'); await W()
    await ev(() => { const $x = $('#d').detach(); $x.appendTo('#desk') })
    await W(300)
    r(t, '.detach().appendTo() while open (same task): dialog stays open, input value kept', await vis(dlg) && (await p.inputValue('#d-input')) === 'Kept' && await ev(() => document.querySelectorAll('[role=dialog]').length === 1))
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'moved dialog still closes on Escape + update:open', (await S()).d === false && !(await vis(dlg)))
    // .detach() and keep it out across frames -> unmount; re-append -> fresh mount
    await p.click('#open-d'); await W(300)
    await ev(() => { window.$held = $('#d').detach() }); await W(300)
    r(t, '.detach() left out: open dialog leaves the page after a frame, body freed', !(await p.$(dlg)) && await bodyFree(), { n: await portalCount(), body: await bodyFree() })
    await ev(() => window.$held.appendTo('#app')); await W(300)
    const ra = await ev(() => ({ dlg: !!document.querySelector('[role=dialog]'), body: !!document.querySelector('#d-body') }))
    r(t, 're-appended after unmount: mounts fresh with slot content (open prop still true -> open)', ra.body, ra)
    await p.keyboard.press('Escape'); await W(300)
    // .remove() while open
    await p.click('#open-d'); await W(300)
    await ev(() => $('#d').remove()); await W(300)
    r(t, '.remove() while open: dialog gone at once, no portal leak, body pointer-events restored', !(await p.$(dlg)) && await bodyFree() && !(await p.$('#d-body')), { body: await bodyFree(), left: await portalCount() })
    r(t, 'page still interactive after .remove() of open modal', await ev(() => document.elementFromPoint(20, 20) !== null) && await (async () => { await p.click('#open-dm'); await W(300); const ok = await vis(dlg); await p.click('#dm-ok button'); await W(300); return ok })())
    // clone
    await ev(() => $('#dm').clone().attr('id', 'dm-clone').attr('title', 'Cloned dialog').appendTo('#desk').prop('modelValue', true)); await W(300)
    r(t, '.clone(): clone opens with its own title, cloned actions slot (es-button) rendered', (await txt(dlg)).includes('Cloned dialog') && await ev(() => !!document.querySelector('[role=dialog] [data-slot=actions] es-button button')), await txt(dlg).catch(() => ''))
    r(t, '.clone(): jQuery handlers are not cloned (as native) -> OK button inert', await (async () => { await p.click(dlg + ' [data-slot=actions] button'); await W(300); return await vis(dlg) })())
    await ev(() => $('#dm-clone').prop('modelValue', false)); await W(300)
    r(t, '.clone() closes through .prop', !(await vis(dlg)))
    // element from a larger template; nested es-text-input + es-dropdown inside an open dialog
    await p.click('#desk-open'); await W(300)
    r(t, 'dialog from a larger HTML template opens with nested es-text-input', await vis('#desk-d-input input') && await inside('#desk-d-input', dlg))
    await p.fill('#desk-d-input input', 'abc')
    r(t, 'nested es-text-input is a Vue child of the dialog (one tree)', await ev(() => { let i = document.getElementById('desk-d-input').esComponent; i = i && i.$; while (i) { if (i.type && (i.type.__name === 'Dialog' || i.type.name === 'Dialog')) return true; i = i.parent } return false }))
    await p.click('#desk-d-dd-btn button'); await W(300)
    r(t, 'nested es-dropdown inside open dialog opens over it', await vis('[role=menu]'))
    await p.click('[role=menuitem]:has-text("Inner B")'); await W(300)
    r(t, 'nested dropdown item fires, dialog stays open', (await log()).includes('inner-b') && await vis(dlg), await log())
    await p.keyboard.press('Escape'); await W(400)
    if (!(await vis(dlg))) await p.click('#desk-open'), await W(300)
    await p.click('#desk-d-save button'); await W(300)
    r(t, 'save button in actions slot reads nested input via jQuery and closes', (await log()).includes('desk-save:abc') && !(await vis(dlg)), await log())
  })

  // ---------- BottomSheet
  t = 'es-bottom-sheet'
  await safe(t, 'core', async () => {
    const s0 = await S()
    await p.click('#open-sheet'); await W(400)
    r(t, 'opens with title', await vis(dlg) && (await txt(dlg)).includes('Sheet title'))
    r(t, 'slot (jQuery-built list) inside sheet, live text', await inside('#sheet-body', dlg) && (await txt('#sheet-body')).replace(/\n/g, ',') === ['1','2','3'].map(i => 'Row ' + i + ' for ' + (s0.name)).join(','), await txt('#sheet-body'))
    const sr = await rect(dlg)
    r(t, 'sits at the bottom of the viewport', sr && sr.y + sr.h >= 880, sr)
    await p.keyboard.press('Escape'); await W(400)
    r(t, 'Escape -> update:open false + after-leave', (await S()).sheet === false && !(await vis(dlg)) && (await log()).includes('sheet-after'))
    await p.click('#open-sheet'); await W(400)
    await p.click('#sheet-close'); await W(400)
    r(t, 'closes from slot button', !(await vis(dlg)))
    await p.click('#open-sheet'); await W(500)
    const hb = await rect(dlg + ' .cursor-grab')
    if (hb) { await p.mouse.move(hb.x + hb.w / 2, hb.y + 10); await p.mouse.down(); for (let i = 1; i <= 10; i++) { await p.mouse.move(hb.x + hb.w / 2, hb.y + 10 + i * 30); await W(16) } await p.mouse.up() }
    await W(500)
    r(t, 'swipe-down on grab handle dismisses', !!hb && (await S()).sheet === false, { hb, s: (await S()).sheet })
    if (await vis(dlg)) { await p.keyboard.press('Escape'); await W(400) }
    await p.click('#open-sheet2'); await W(400)
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'dismissible="false" ignores Escape', await vis(dlg) && await vis('#sheet2-body'))
    await p.click('#sheet2-close'); await W(400)
    r(t, 'sheet2 closes', !(await vis(dlg)))
  })
  desk(t, async (t) => {
    await ev(() => $('#sheet-body').append('<li id="sheet-r4">Row 4 appended</li>'))
    await ev(() => $('#sheet').prepend('<p id="sheet-pre">prepended</p>'))
    await p.click('#open-sheet'); await W(400)
    r(t, 'jQuery .append() into slot node and .prepend() into host show up', await inside('#sheet-r4', dlg) && await inside('#sheet-pre', dlg) && await ev(() => { const a = document.getElementById('sheet-pre'), b = document.getElementById('sheet-body'); return !!(a.compareDocumentPosition(b) & 4) }))
    await ev(() => $('#sheet').detach().appendTo('#desk')); await W(300)
    r(t, '.detach().appendTo() while open keeps it open', await vis(dlg))
    await ev(() => $('#sheet').remove()); await W(400)
    r(t, '.remove() while open: sheet gone, body free', !(await p.$(dlg)) && await bodyFree())
  })

  // ---------- Popover
  t = 'es-popover'
  await safe(t, 'core', async () => {
    const trig = await rect('#pop-trigger button')
    r(t, 'trigger es-button in slot="trigger" renders', !!trig && trig.w > 20, trig)
    await p.click('#pop-trigger button'); await W(300)
    r(t, 'opens on trigger click: update:open + open event', await vis('#pop-body') && (await S()).pop === true && (await log()).includes('pop-open'))
    const pr = await rect('[data-slot=content]:has(#pop-body)')
    r(t, 'content positioned under its trigger', pr && trig && Math.abs(pr.x - trig.x) < 20 && pr.y >= trig.y + trig.h - 2 && pr.y < trig.y + trig.h + 30, { trig, pr })
    r(t, 'arrow rendered', !!(await p.$('[data-slot=arrow]')))
    r(t, 'aria-expanded on the real trigger button', await ev(() => document.querySelector('#pop-trigger button').getAttribute('aria-expanded') === 'true'))
    await p.click('#pop-rename'); await W()
    r(t, 'jQuery handler in popover slot runs', (await txt('#pop-body')).includes('Linus'))
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'Escape closes + close event', !(await vis('#pop-body')) && (await S()).pop === false && (await log()).includes('pop-close'))
    await p.focus('#pop-trigger button'); await p.keyboard.press('Enter'); await W(300)
    r(t, 'opens from keyboard (Enter on trigger)', await vis('#pop-body'))
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'focus returns to the trigger button after Escape', await ev(() => !!(document.activeElement && document.activeElement.closest('#pop-trigger'))))
    r(t, 'exposed close() on the element', await ev(() => typeof document.getElementById('pop').close === 'function'), await ev(() => Object.keys(document.getElementById('pop').esComponent?.$?.exposed || {}).join(',')))
    await p.click('#pop-trigger button'); await W(300)
    await ev(() => document.getElementById('pop').close()); await W(300)
    r(t, 'el.close() closes it', !(await vis('#pop-body')))
    await p.click('#pop2-trigger'); await W(300)
    r(t, 'controlled bare popover opens', await vis('#pop2-body'))
    r(t, 'bare: no PopoverPanel shell', !(await p.$('[data-slot=content]:has(#pop2-body) [data-slot=panel]')))
    await p.mouse.click(5, 880); await W(300)
    r(t, 'dismissible="false" ignores outside click', await vis('#pop2-body'))
    await p.click('#pop2-close'); await W(300)
    r(t, 'controlled popover closes from .prop("open", false)', !(await vis('#pop2-body')))
    await ev(() => $('#pop2').prop('open', true)); await W(300)
    r(t, 'opens from .prop("open", true)', await vis('#pop2-body'))
    await ev(() => $('#pop2').prop('open', false)); await W(300)
  })
  desk(t, async (t) => {
    // jQuery inserts content above an open popover's trigger (layout shift)
    await p.click('#pop-trigger button'); await W(300)
    const tr0 = await rect('#pop-trigger button')
    await ev(() => $('<div id="shift" style="height:120px">shift</div>').insertBefore($('#pop').parent())); await W(400)
    const tr1 = await rect('#pop-trigger button'), pr1 = await rect('[data-slot=content]:has(#pop-body)')
    r(t, 'layout shift (jQuery .insertBefore above the open trigger): content follows', tr1 && pr1 && tr1.y - tr0.y > 100 && Math.abs(pr1.y - (tr1.y + tr1.h)) < 30, { tr0, tr1, pr1 })
    await ev(() => $('#shift').remove()); await W(300)
    // detach/appendTo while open: stays open and re-anchors
    await ev(() => $('#pop').detach().appendTo('#desk')); await W(400)
    const tr2 = await rect('#pop-trigger button'), pr2 = await rect('[data-slot=content]:has(#pop-body)')
    r(t, '.detach().appendTo() while open: stays open, content follows the moved trigger', await vis('#pop-body') && pr2 && tr2 && Math.abs(pr2.x - tr2.x) < 20 && Math.abs(pr2.y - (tr2.y + tr2.h)) < 30, { tr2, pr2 })
    await p.keyboard.press('Escape'); await W(300)
    // .html(): replace trigger + body
    await ev(() => $('#pop').html('<button slot="trigger" id="pop-t3" class="border px-2">New trigger</button><div id="pop-b3" class="p-2">New body</div>')); await W(100)
    await p.click('#pop-t3'); await W(300)
    r(t, '.html() with new slot="trigger" + body: works as a popover', await vis('#pop-b3'))
    await p.keyboard.press('Escape'); await W(300)
    // clone
    await ev(() => $('#pop2').clone().attr('id', 'pop2c').appendTo('#desk')); await W(100)
    await ev(() => $('#pop2c button[slot=trigger], #pop2c [slot=trigger]').first().attr('id', 'pop2c-t'))
    await p.click('#pop2c-t').catch(() => {}); await W(300)
    r(t, '.clone(): clone opens its own popover (dup ids aside)', await ev(() => [...document.querySelectorAll('[data-slot=content]')].some((c) => c.innerText.includes('Bare popover'))))
    await ev(() => $('#pop2c').remove()); await W(300)
    r(t, '.remove() of open clone: content gone', !(await ev(() => [...document.querySelectorAll('[data-slot=content]')].some((c) => c.innerText.includes('Bare popover')))))
    // nested es-dropdown in popover from a larger template
    await p.click('#desk-pop-trigger'); await W(300)
    await p.click('#desk-pop-dd button'); await W(300)
    r(t, 'nested es-dropdown inside an open popover opens', await vis('[role=menu]'))
    await p.click('[role=menuitem]:has-text("Pop item")'); await W(300)
    r(t, 'nested dropdown item fires', (await log()).includes('pop-item'))
    await p.keyboard.press('Escape'); await W(200); await p.mouse.click(5, 880); await W(300)
    // .remove() while open
    await p.click('#pop-t3'); await W(300)
    await ev(() => $('#pop').remove()); await W(300)
    r(t, '.remove() while open: content gone at once', !(await p.$('#pop-b3')) && !(await ev(() => [...document.querySelectorAll('[data-slot=content]')].some((c) => c.innerText.includes('New body')))))
  })

  // ---------- HoverCard
  t = 'es-hover-card'
  await safe(t, 'core', async () => {
    const ht = await rect('#hc-trigger')
    await p.hover('#hc-trigger'); await W(500)
    r(t, 'opens on hover', await vis('#hc-body') && (await S()).hc === true)
    const hr = await rect('[data-slot=content]:has(#hc-body)')
    r(t, 'positioned under trigger', hr && ht && Math.abs(hr.x - ht.x) < 30 && hr.y >= ht.y + ht.h - 2 && hr.y < ht.y + ht.h + 40, { ht, hr })
    await p.hover('#far'); await W(600)
    r(t, 'closes on leave', !(await vis('#hc-body')) && (await S()).hc === false)
    await p.focus('#hc-trigger'); await W(400)
    r(t, 'opens on keyboard focus', await vis('#hc-body'))
    await ev(() => document.activeElement.blur()); await W(500)
    r(t, 'closes on blur', !(await vis('#hc-body')))
  })
  desk(t, async (t) => {
    await ev(() => $('#hc').clone().attr('id', 'hc2').appendTo('#desk')); await ev(() => $('#hc2 [slot=trigger], #hc2 a').first().attr('id', 'hc2-t'))
    await p.hover('#hc2-t'); await W(500)
    r(t, '.clone(): clone hovers open its own card', await ev(() => [...document.querySelectorAll('[data-slot=content]')].some((c) => c.innerText.includes('Hover card'))))
    await ev(() => $('#hc2').remove()); await W(300)
    r(t, '.remove() while open: card gone', !(await ev(() => [...document.querySelectorAll('[data-slot=content]')].some((c) => c.innerText.includes('Hover card')))))
  })
  // Desk-style operations last: a failure there must not hide the ports' results
  for (const [t, f] of later) await safe(t, 'desk ops', () => f(t))
})
