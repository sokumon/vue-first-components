// jQuery-driven re-run of wc/sweep/overlays/t-baseline.cjs
require('./lib.cjs')('baseline.html', async ({ p, r, txt, st, ev, W, vis, rect, inside, log, safe }) => {
  const t = 'baseline'
  const state = () => txt('#state')
  await safe(t, 'all', async () => {
    r('es-button', 'label prop renders', (await txt('#b-label')) === 'Label prop')
    r('es-button', 'default slot renders', (await txt('#b-slot')).includes('Slot text'))
    r('es-button', 'tailwind applied', await p.$eval('#b-label button', (e) => getComputedStyle(e).backgroundColor !== 'rgba(0, 0, 0, 0)'))
    await p.click('#b-load button'); await W(100)
    r('es-button', '.attr("loading", "") from a jQuery click -> disabled spinner', await p.$eval('#b-load button', (e) => e.disabled).catch(() => false))
    await p.fill('#ti input', 'Grace'); await W(50)
    r('es-text-input', 'update:modelValue -> page state', (await state()).startsWith('Grace|'), await state())
    r('es-checkbox', 'starts unchecked (prop false)', !(await p.$eval('#cb input', (e) => e.checked)))
    r('es-fw-check-field', 'starts unchecked (model 0)', !(await p.$eval('#fw input', (e) => e.checked)))
    await p.click('#cb input'); await W(50)
    r('es-checkbox', 'v-model', (await state()).split('|')[1] === 'true')
    await p.click('#sw button, #sw [role=switch]'); await W(50)
    r('es-switch', 'v-model', (await state()).split('|')[2] === 'true')
    await p.click('#sel button, #sel [role=combobox]'); await W(300)
    await p.click('[role=option]:has-text("Blue")'); await W(100)
    r('es-select', 'options prop + v-model', (await state()).split('|')[3] === 'blue', await state())
    r('es-badge', 'renders', (await txt('#badge')) === 'Draft')
    r('es-avatar', 'renders', (await p.$eval('#av', (e) => e.innerHTML.length)) > 20)
    await p.click('#dd button'); await W(300)
    await p.click('[role=menuitem]:has-text("Delete")'); await W(100)
    r('es-dropdown', 'function in options fires', (await st()).picked === 'Delete')
    await p.click('#open-dlg button'); await W(400)
    const dlg = await p.$('[role=dialog]')
    r('es-dialog', 'opens via .prop from es-button click', !!dlg)
    r('es-dialog', 'title prop', !!dlg && (await dlg.innerText()).includes('Hello from es-dialog'))
    r('es-dialog', 'body slot inside teleported dialog, text current', !!dlg && (await dlg.innerText()).includes('name=Grace'))
    await p.click('#dlg-rename button'); await W(100)
    r('es-dialog', 'nested es-button in slot drives page state', (await txt('#dlg-body')).includes('name=Linus') && (await state()).startsWith('Linus|'))
    r('es-button', 'slot text updated by jQuery', (await txt('#b-dyn')) === 'Hi Linus')
    await p.keyboard.press('Escape'); await W(300)
    r('es-dialog', 'Escape -> update:open -> page state', (await state()).split('|')[4] === 'false')
    await p.click('#fw input'); await W(50)
    r('es-fw-check-field', '(0|1) v-model', (await state()).split('|')[5] === '1', await state())
    const before = await ev(() => ({ body: document.body.children.length, dialogs: document.querySelectorAll('[role=dialog]').length }))
    await p.click('#show-dlg2 button'); await W(400)
    const d2 = await p.$('[role=dialog]:has-text("Second dialog")')
    r('es-dialog', 'created open from an HTML string (open attribute), slot current', !!d2 && (await d2.innerText()).includes('name=Linus'))
    await p.click('#dlg2-kill button'); await W(400)
    const after = await ev(() => ({ host: !!document.getElementById('dlg2'), body: document.body.children.length, dialogs: document.querySelectorAll('[role=dialog]').length, kill: !!document.getElementById('dlg2-kill'), pe: getComputedStyle(document.body).pointerEvents }))
    r('es-dialog', '$d2.remove() from its own nested button: unmounted, no leaked teleport, body interactive', !after.host && !after.kill && after.dialogs === before.dialogs && after.body === before.body && after.pe !== 'none', { before, after })
  })
})
