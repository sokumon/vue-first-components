// jQuery-driven re-run of wc/sweep/overlays/t-menus.cjs + Desk-style operations.
require('./lib.cjs')('menus.html', async ({ p, r, txt, st, ev, W, vis, rect, inside, log, safe }) => {
  const menu = '[role=menu]'
  const later = []
  const desk = (t, f) => later.push([t, f])
  let t = 'es-dropdown'
  await safe(t, 'core', async () => {
    const tr = await rect('#dd-trigger button')
    r(t, 'trigger: es-button in default slot renders', tr && tr.w > 20 && (await txt('#dd-trigger')).includes('Menu'), tr)
    await p.click('#dd-trigger button'); await W(300)
    r(t, 'opens on click -> update:open', await vis(menu) && (await st()).dd === true)
    const mr = await rect(menu)
    r(t, 'menu positioned under trigger', mr && tr && Math.abs(mr.x - tr.x) < 20 && mr.y >= tr.y + tr.h - 2 && mr.y < tr.y + tr.h + 30, { tr, mr })
    r(t, 'trigger button carries aria-expanded / data-state=open', await p.$eval('#dd-trigger button', (b) => b.getAttribute('aria-expanded') + '/' + b.getAttribute('data-state')).then((v) => v === 'true/open'))
    r(t, 'group labels rendered', (await txt(menu)).includes('Actions') && (await txt(menu)).includes('Danger'), await txt(menu))
    r(t, 'per-item named slot (option.slot -> slot="item-danger") inside its row', await inside('#dd-danger', menu) && (await txt('#dd-danger')).startsWith('Delete forever'))
    await p.keyboard.press('ArrowDown'); await W(80)
    const f1 = await ev(() => document.activeElement && document.activeElement.innerText.trim())
    r(t, 'ArrowDown moves focus into menu', /Edit|Share/.test(f1 || ''), f1)
    await p.hover(menu + ' [role=menuitem]:has-text("Share")'); await W(400)
    r(t, 'submenu opens on hover', await vis('[role=menu] [role=menuitem]:has-text("Email")'))
    await p.click('[role=menuitem]:has-text("Email")'); await W(300)
    r(t, 'submenu item onClick (fn via .prop) fires, menu closes', (await log()).includes('email') && !(await vis(menu)) && (await st()).dd === false)
    await p.click('#dd-trigger button'); await W(300)
    await p.click(menu + ' [role=switch]'); await W(200)
    r(t, 'switch item toggles page state through onClick(value)', (await st()).notify === false, await log())
    await p.keyboard.press('Escape'); await W(300)
    r(t, 'Escape closes', !(await vis(menu)) && (await st()).dd === false)
    r(t, 'focus returns to trigger button after Escape', await ev(() => !!(document.activeElement && document.activeElement.closest('#dd-trigger'))))
    await p.focus('#dd-trigger button'); await p.keyboard.press('Enter'); await W(300)
    r(t, 'opens from keyboard (Enter)', await vis(menu))
    await p.keyboard.press('Escape'); await W(300)
    await p.click('#dd-open'); await W(300)
    r(t, 'opens from .prop("open", true)', await vis(menu))
    await p.click(menu + ' [role=menuitem]:has-text("Delete")'); await W(300)
    r(t, 'item with slot clicked -> onClick', (await log()).includes('delete') && !(await vis(menu)))
    r(t, 'slot node text kept live by jQuery (.logn)', (await txt('#dd-danger')).includes('(' + (await st()).log.length + ')'), await txt('#dd-danger'))
    await p.click('#dd2-trigger'); await W(300)
    r(t, 'slot="trigger" plain button opens dropdown', await vis(menu))
    r(t, 'slot="empty" rendered in empty menu', await inside('#dd2-empty', menu) && await vis('#dd2-empty'))
    const t2 = await rect('#dd2-trigger'), m2 = await rect(menu)
    r(t, 'empty menu positioned under slot trigger', m2 && t2 && Math.abs(m2.x - t2.x) < 20 && m2.y >= t2.y + t2.h - 2 && m2.y < t2.y + t2.h + 30, { t2, m2 })
    await p.keyboard.press('Escape'); await W(300)
    const b3 = await p.$('#dd3 button')
    r(t, 'button attribute as JSON (button=\'{"label":…}\') renders the trigger label', !!b3 && (await txt('#dd3')).includes('Suffix menu'), await txt('#dd3'))
    if (b3) {
      await p.click('#dd3 button'); await W(300)
      const n = await p.$$eval(menu + ' .dd-suffix', (es) => es.length)
      r(t, 'item-suffix: one plain light-DOM node rendered per row (later rows get clones)', n === 3, n + ' of 3; ' + await txt(menu))
      await p.keyboard.press('Escape'); await W(300)
    }
    const b4 = await p.$('#dd4 button')
    if (b4) {
      await p.click('#dd4 button'); await W(300)
      const rows = await p.$$eval(menu + ' .dd4-suffix', (es) => es.map((e) => e.textContent + ':' + e.getAttribute('data-row')))
      r(t, 'item-suffix <template slot> stamped per row with scope (data-es-text + es-slot event)', rows.join() === 'One:One,Two:Two,Three:Three', rows)
      await p.keyboard.press('Escape'); await W(300)
    } else r(t, 'item-suffix <template slot> (trigger missing)', false)
    // set button/options after creation via .prop (the working path)
    await ev(() => $('#dd3').prop('button', { label: 'Suffix via prop' })); await W(100)
    r(t, '.prop("button", {...}) sets the trigger label', (await txt('#dd3')).includes('Suffix via prop'), await txt('#dd3'))
  })
  desk(t, async (t) => {
    // per-row dropdowns in a list built from an HTML string
    await p.click('.list-row[data-name="ToDo-2"] .row-dd-btn button'); await W(300)
    const rr = await rect('.list-row[data-name="ToDo-2"] .row-dd-btn button'), mm = await rect(menu)
    r(t, 'row dropdown from an HTML string template opens under its row trigger', await vis(menu) && mm && rr && Math.abs(mm.y - (rr.y + rr.h)) < 30, { rr, mm })
    await p.click('[role=menuitem]:has-text("Open")'); await W(300)
    r(t, 'row item onClick sees its closure row', (await log()).includes('open:ToDo-2'))
    await p.click('.list-row[data-name="ToDo-1"] .row-dd-btn button'); await W(300)
    await p.click('[role=menuitem]:has-text("Delete")'); await W(400)
    r(t, 'row Delete item does $row.remove() from inside its own menu: row gone, menu gone, no error', !(await p.$('.list-row[data-name="ToDo-1"]')) && !(await vis(menu)) && (await log()).includes('del:ToDo-1'))
    r(t, 'body interactive after removal (pointer-events)', await ev(() => getComputedStyle(document.body).pointerEvents !== 'none'))
    // .prop options update while open
    await p.click('#dd-trigger button'); await W(300)
    await ev(() => $('#dd').prop('options', [{ label: 'Replaced', onClick: () => S.log.push('replaced') }])); await W(200)
    r(t, '.prop("options") while open re-renders the open menu', (await txt(menu)).includes('Replaced') && !(await txt(menu)).includes('Share'), await txt(menu))
    await p.click('[role=menuitem]:has-text("Replaced")'); await W(300)
    r(t, 'replaced item fires', (await log()).includes('replaced'))
    // layout shift while open
    await p.click('#dd-trigger button'); await W(300)
    await ev(() => $('<div id="shift" style="height:100px">shift</div>').insertBefore($('#dd').parent())); await W(400)
    const tr1 = await rect('#dd-trigger button'), m1 = await rect(menu)
    r(t, 'layout shift above the open trigger: menu follows', tr1 && m1 && Math.abs(m1.y - (tr1.y + tr1.h)) < 30, { tr1, m1 })
    await p.keyboard.press('Escape'); await W(300)
    await ev(() => $('#shift').remove())
    // .detach()/.appendTo() closed, then opens in new place
    await ev(() => $('#dd').detach().appendTo('#desk')); await W(100)
    await p.click('#dd-trigger button'); await W(300)
    const tr2 = await rect('#dd-trigger button'), m3 = await rect(menu)
    r(t, '.detach().appendTo(): moved dropdown opens under its new place', m3 && tr2 && Math.abs(m3.y - (tr2.y + tr2.h)) < 30 && Math.abs(m3.x - tr2.x) < 30, { tr2, m3 })
    // .remove() while open
    await ev(() => $('#dd').remove()); await W(300)
    r(t, '.remove() while open: menu gone, body interactive', !(await p.$(menu)) && await ev(() => getComputedStyle(document.body).pointerEvents !== 'none'))
    // .clone() of a dropdown with a plain trigger
    await ev(() => { const $c = $('#dd2').clone(); $c.attr('id', 'dd2c').find('#dd2-trigger').attr('id', 'dd2c-trigger'); $c.find('#dd2-empty').attr('id', 'dd2c-empty'); $c.appendTo('#desk').prop('options', [{ label: 'Clone item', onClick: () => S.log.push('clone-item') }]) }); await W(100)
    await p.click('#dd2c-trigger'); await W(300)
    r(t, '.clone() + .prop("options"): clone opens its own menu', (await txt(menu).catch(() => '')).includes('Clone item'), await txt(menu).catch(() => ''))
    await p.click('[role=menuitem]:has-text("Clone item")'); await W(300)
    r(t, 'clone item fires', (await log()).includes('clone-item'))
    // .html() on a dropdown host: new trigger
    await ev(() => $('#dd2').html('<button slot="trigger" id="dd2-new" class="border px-2">New trigger</button>')); await W(100)
    await p.click('#dd2-new'); await W(300)
    r(t, '.html() with a new slot="trigger": opens', await vis(menu))
    await p.keyboard.press('Escape'); await W(300)
    // .empty(): no trigger left; must not throw; then append a trigger back
    await ev(() => $('#dd2').empty().append('<button slot="trigger" id="dd2-back" class="border px-2">Back</button>')); await W(100)
    await p.click('#dd2-back'); await W(300)
    r(t, '.empty().append(trigger): opens again', await vis(menu))
    await p.keyboard.press('Escape'); await W(300)
  })

  t = 'es-context-menu'
  await safe(t, 'core', async () => {
    const a = await rect('#cm-area')
    await p.click('#cm-area', { button: 'right', position: { x: 40, y: 20 } }); await W(300)
    r(t, 'opens on right click -> update:open', await vis(menu) && (await st()).cm === true)
    const cr = await rect(menu)
    r(t, 'menu at pointer', cr && Math.abs(cr.x - (a.x + 40)) < 10 && Math.abs(cr.y - (a.y + 20)) < 10, { a, cr })
    r(t, 'disabled option is disabled', await p.$eval(menu + ' [role=menuitem]:has-text("Paste")', (e) => e.hasAttribute('data-disabled') || e.getAttribute('aria-disabled') === 'true').catch(() => false))
    await p.keyboard.press('ArrowDown'); await p.keyboard.press('Enter'); await W(300)
    r(t, 'keyboard select Copy', (await log()).includes('copy') && !(await vis(menu)) && (await st()).cm === false, await log())
    r(t, 'region slot text kept live by jQuery', (await txt('#cm-area')).includes('(' + (await st()).log.length + ')'), await txt('#cm-area'))
    await p.click('#cm-area', { button: 'right' }); await W(300)
    await p.hover(menu + ' [role=menuitem]:has-text("More")'); await W(400)
    await p.click('[role=menuitem]:has-text("Deep")'); await W(300)
    r(t, 'submenu item', (await log()).includes('deep'), await log())
  })
  desk(t, async (t) => {
    // jQuery .append() a new row into the region; right-click on it still opens the menu
    await ev(() => $('#cm-area').append('<div id="cm-row" class="p-2 border">appended row</div>'))
    await p.click('#cm-row', { button: 'right' }); await W(300)
    r(t, 'right-click on content jQuery appended into the region opens', await vis(menu))
    await p.keyboard.press('Escape'); await W(300)
    // .html() on host: new region
    await ev(() => $('#cm').html('<div id="cm-area2" class="border p-6 w-60">New region</div>')); await W(100)
    await p.click('#cm-area2', { button: 'right' }); await W(300)
    r(t, '.html() on host: new region opens the menu', await vis(menu))
    await p.keyboard.press('Escape'); await W(300)
    // .clone()
    await ev(() => { const $c = $('#cm').clone(); $c.attr('id', 'cmc').find('#cm-area2').attr('id', 'cmc-area'); $c.appendTo('#desk').prop('options', [{ label: 'Cloned ctx', onClick: () => S.log.push('cloned-ctx') }]) }); await W(100)
    await p.click('#cmc-area', { button: 'right' }); await W(300)
    r(t, '.clone(): clone region opens its own menu', (await txt(menu).catch(() => '')).includes('Cloned ctx'))
    await p.click('[role=menuitem]:has-text("Cloned ctx")'); await W(300)
    r(t, 'cloned menu item fires', (await log()).includes('cloned-ctx'))
    // .remove() while open
    await p.click('#cmc-area', { button: 'right' }); await W(300)
    await ev(() => $('#cmc').remove()); await W(300)
    r(t, '.remove() while open: menu gone, body interactive', !(await p.$(menu)) && await ev(() => getComputedStyle(document.body).pointerEvents !== 'none'))
  })
  for (const [t, f] of later) await safe(t, 'desk ops', () => f(t))
})
